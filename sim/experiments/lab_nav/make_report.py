"""Build outputs/lab_nav_20261105/RESULTS.md from the verification records.

Every number in the report is read from a JSON file this project wrote; nothing is
typed in by hand.  Re-run it after any batch and the tables follow the data.
"""
import json
from pathlib import Path

WS = Path(__file__).resolve().parents[3]
OUT = WS / "outputs" / "lab_nav_20261105"
RL = OUT / "rl"


def load(p, default=None):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else default


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def batch_rows(per_goal, order=None):
    rows = []
    names = order or list(per_goal)
    for name in names:
        p = per_goal.get(name)
        if not p:
            continue
        rows.append([name, f"{p['target'][0]:.2f}, {p['target'][1]:.2f}",
                     f"{p['successes']}/{p['attempts']}",
                     f"{p['mean_final_error_m']:.3f}",
                     f"{p['mean_sim_seconds']:.1f}",
                     f"{p['mean_path_m']:.2f}"])
    return rows


def main():
    lines = ["# Results - lab_nav_20261105", "",
             "Generated by `sim/experiments/lab_nav/make_report.py` from the JSON "
             "records in this directory.  Prose that explains a choice lives in "
             "`README.md`; this file only restates what the files say.", ""]

    t4 = load(OUT / "task4_verification.json", {})
    t5 = load(OUT / "task5_verification.json", {})
    t6 = load(OUT / "task6_verification.json", {})
    t7 = load(OUT / "task7_verification.json", {})

    lines += ["## Navigation, truth localisation", ""]
    overall = t4.get("overall", {})
    lines.append(f"{overall.get('successes')}/{overall.get('attempts')} goals reached, "
                 f"{overall.get('false_successes')} reported success contradicted by the "
                 f"truth, {overall.get('stuck_rounds')} rounds with wheels turning and the "
                 f"body still.")
    lines.append("")
    if overall.get("per_goal"):
        lines.append(table(batch_rows(overall["per_goal"]),
                           ["goal", "target (x, y)", "reached", "mean final error (m)",
                            "mean sim time (s)", "mean path (m)"]))
        lines.append("")

    lines += ["## Navigation, AMCL", ""]
    nav = t5.get("navigation_repeats", {})
    lines.append(f"{nav.get('successes')}/{nav.get('attempts')} with AMCL against "
                 f"{nav.get('truth_baseline_for_comparison', {}).get('successes')}/"
                 f"{nav.get('truth_baseline_for_comparison', {}).get('attempts')} for the "
                 f"same goals under truth localisation.")
    lines.append("")
    if nav.get("per_goal"):
        lines.append(table(batch_rows(nav["per_goal"]),
                           ["goal", "target (x, y)", "reached", "mean final error (m)",
                            "mean sim time (s)", "mean path (m)"]))
        lines.append("")
    static = t5.get("static_test", {})
    straight = t5.get("straight_line_test", {})
    lines.append(f"Localisation: static {static.get('max_error_m')} m over "
                 f"{static.get('samples')} samples (drift {static.get('drift_m')} m); "
                 f"after {straight.get('travelled_m')} m straight the estimate is "
                 f"{straight.get('end_error_m')} m from the truth.")
    lines.append("")

    lines += ["## Perception profiles", ""]
    prof = t6.get("profiles") or {}
    if prof:
        rows = []
        for name, p in prof.items():
            topics = p.get("topics") or {}

            def hz(pattern):
                # The full-sensor world names its topics /hz_sim/full/..., the lean
                # one /scan, so match on the tail rather than on a fixed key.
                for key, t in topics.items():
                    if not key.endswith(pattern):
                        continue
                    value = t.get("hz")
                    if value is None:
                        continue
                    nominal = t.get("nominal_hz")
                    return f"{value} / {nominal}" if nominal else f"{value}"
                return "-"

            rows.append([name, p.get("rtf"),
                         hz("/scan") if hz("/scan") != "-" else hz("/lidar/points"),
                         hz("/image"), hz("/imu")])
        lines.append(table(rows, ["profile", "realtime factor", "scan Hz",
                                  "camera Hz", "IMU Hz"]))
        lines.append("")
        lines.append("Values are measured / nominal.  A ratio near 1 means frames "
                     "arrived at the advertised rate; a lower ratio means frames were "
                     "dropped, not that simulated time slowed down.")
    else:
        lines.append("see `task6_verification.json`")
    lines.append("")

    lines += ["## Reinforcement learning", ""]
    runs = t7.get("runs") or []
    if runs:
        for run in runs:
            ev = run.get("evaluation") or {}
            train = run.get("training") or {}
            lines.append(f"**{run.get('run')}** - {train.get('total_timesteps')} steps, "
                         f"seed {train.get('seed')}, "
                         f"{train.get('train_goals')} training goals, "
                         f"{train.get('wall_seconds')} s of wall clock.")
            lines.append("")
            rows = []
            for key, label in (("eval_goals", "three fixed goals"),
                               ("train_near", "goals used in training"),
                               ("held_out", "held-out goals"),
                               ("constant_forward", "constant-forward control")):
                s = ev.get(key)
                if not s:
                    continue
                rows.append([label, f"{s['successes']}/{s['attempts']}",
                             f"{s['mean_final_distance_m']:.2f}",
                             f"{s['mean_path_m']:.2f}",
                             f"{s['mean_sim_seconds']:.1f}"])
            if rows:
                lines.append(table(rows, ["set", "reached", "mean final distance (m)",
                                          "mean path (m)", "mean sim time (s)"]))
                lines.append("")
            curve = run.get("learning_curve") or {}
            if curve.get("bins"):
                lines.append(f"Episodes {curve['episodes']}, arrival rate "
                             f"{curve['arrival_rate']}, contact rate {curve['contact_rate']}.")
                lines.append("")
                lines.append(table([[b["from_step"], b["episodes"], f"{b['mean_return']:+.2f}",
                                     b["arrived"], b["contact"]] for b in curve["bins"]],
                                   ["from step", "episodes", "mean return", "arrived",
                                    "contact"]))
                lines.append("")
        for line in t7.get("reading") or []:
            lines.append(f"- {line}")
        lines.append("")
        cmp_ = t7.get("comparison_with_the_baseline", {})
        lines.append(f"Baseline on the same world: {cmp_.get('baseline')}.  "
                     f"{cmp_.get('not_a_fair_comparison_yet')}")
    else:
        lines.append("no evaluation recorded yet")
    lines.append("")

    lines += ["## Open issues carried in the records", ""]
    for name, doc in (("task4", t4), ("task5", t5), ("task6", t6), ("task7", t7)):
        corr = doc.get("collision_source_correction")
        if corr:
            lines.append(f"- {name}: the collision figure was not measured - "
                         f"{corr.get('issue')}")
            break
    for name, doc in (("task4", t4), ("task5", t5)):
        for f in doc.get("failures", []) or []:
            lines.append(f"- {name} failure: {f.get('goal')} round {f.get('round')} - "
                         f"{f.get('reason')} at {f.get('final_error_m')} m after "
                         f"{f.get('sim_seconds')} simulated seconds")
    lines.append("")

    (OUT / "RESULTS.md").write_text("\n".join(lines), newline="\n")
    print(json.dumps({"written": str(OUT / "RESULTS.md"), "lines": len(lines)}))


if __name__ == "__main__":
    main()
